import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import {stageUi} from './stage.ts';

function fixture(t: any, mode = 'success') {
  const root = mkdtempSync('/tmp/apparent-dev-ui-stage-');
  t.after(() => rmSync(root, {recursive: true, force: true}));
  const put = (name: string, bytes: string) => {
    const path = resolve(root, name);
    mkdirSync(dirname(path), {recursive: true}); writeFileSync(path, bytes); return path;
  };
  const resources = resolve(root, 'App.app/Contents/Resources');
  put('App.app/Contents/Resources/note-ui/old-runtime', 'previous package');
  put('capture/desktop/ui/frontend/dist/index.html', 'stale renderer');
  // Synthetic Settings producer replaces old generated bytes. The coordinator
  // and popup staging execute unmodified, without npm, Apple tools or a GUI.
  put('capture/desktop/enablement/packaging/stage-settings.py', `
import json, sys
from pathlib import Path
root = Path(__file__).resolve().parents[4]
with (root / 'calls').open('a') as trace: trace.write(json.dumps(sys.argv[1:]) + '\\n')
if ${JSON.stringify(mode)} == 'failed': sys.exit(19)
frontend = root / 'capture/desktop/ui/frontend'
for name in ['dist/index.html', 'electron/runtime.cjs', 'electron/notes/main.cjs', 'electron/notes/presentation.cjs', 'electron/notes/lifecycle.cjs']:
    if ${JSON.stringify(mode)} == 'missing' and name.endswith('main.cjs'): continue
    output = frontend / name
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('fresh ' + name)
settings = Path(sys.argv[1]) / 'app/dist/settings.html'
settings.parent.mkdir(parents=True, exist_ok=True)
settings.write_text('fresh Settings')
`);
  return {root, resources, put};
}

test('one fresh preparation supplies Settings and popup payloads with signing arguments intact', async t => {
  const f = fixture(t);
  const signing = ['--sign', 'Developer ID Application: Synthetic', '--keychain', '/synthetic/private keychain'];
  const cli = f.put('capture/desktop/enablement/packaging/frontend/stage.ts', readFileSync(new URL('./stage.ts', import.meta.url), 'utf8'));
  f.put('capture/desktop/ui/frontend/scripts/popup-entries.mjs',
    readFileSync(new URL('../../../ui/frontend/scripts/popup-entries.mjs', import.meta.url), 'utf8'));
  const result = spawnSync(process.execPath, ['--experimental-strip-types', cli, f.resources, ...signing],
    {cwd: f.root, encoding: 'utf8'});
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.deepEqual(readFileSync(resolve(f.root, 'calls'), 'utf8').trim().split('\n').map(line => JSON.parse(line)),
    [[resolve(f.resources, 'settings'), ...signing]]);
  assert.equal(readFileSync(resolve(f.resources, 'settings/app/dist/settings.html'), 'utf8'), 'fresh Settings');
  for (const name of ['dist/index.html', 'electron/runtime.cjs', 'electron/notes/main.cjs', 'electron/notes/presentation.cjs', 'electron/notes/lifecycle.cjs'])
    assert.equal(readFileSync(resolve(f.resources, 'note-ui', name), 'utf8'), 'fresh ' + name);
  assert.throws(() => readFileSync(resolve(f.resources, 'note-ui/old-runtime')), /ENOENT/);
});

test('failed preparation cannot stage stale popup output or replace its previous destination', async t => {
  const f = fixture(t, 'failed');
  await assert.rejects(stageUi(f.root, f.resources, ['--sign', '-']), /Command failed/);
  assert.equal(readFileSync(resolve(f.resources, 'note-ui/old-runtime'), 'utf8'), 'previous package');
  assert.throws(() => readFileSync(resolve(f.resources, 'note-ui/dist/index.html')), /ENOENT/);
});

test('incomplete fresh output fails popup staging', async t => {
  const f = fixture(t, 'missing');
  await assert.rejects(stageUi(f.root, f.resources, ['--sign', '-']), /ENOENT/);
  assert.equal(readFileSync(resolve(f.resources, 'note-ui/old-runtime'), 'utf8'), 'previous package');
});

test('popup destination safety remains enforced after fresh Settings preparation', async t => {
  const f = fixture(t);
  rmSync(resolve(f.resources, 'note-ui'), {recursive: true});
  const outside = f.put('outside/preserved', 'untouched');
  symlinkSync(dirname(outside), resolve(f.resources, 'note-ui'));
  await assert.rejects(stageUi(f.root, f.resources, ['--sign', '-']), /Unsafe popup/);
  assert.equal(readFileSync(outside, 'utf8'), 'untouched');
});
